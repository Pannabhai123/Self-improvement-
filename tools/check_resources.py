#!/usr/bin/env python3
"""
Static cross-reference audit for the Focus Life Android project.

There is no JDK or Android SDK in this sandbox and every binary host is
firewalled, so `aapt2`/`javac` cannot run here. This script reproduces the part
of the build that fails most often and is cheapest to check statically:

  1. Every `R.<type>.<name>` referenced from Java exists in `res/`.
  2. Every `@<type>/<name>` referenced from XML exists in `res/`.
  3. Every custom view attribute (`app:prv_*`, `app:bcv_*`, `app:wsv_*`) used in
     a layout is declared in `values/attrs.xml`.
  4. Every `android:id="@+id/x"` in a layout resolves to the binding field name
     ViewBinding will generate, and every `binding.<field>` used in Java exists.
  5. English and Hindi string files are in parity, including `%n$x` placeholders.
  6. No CJK contamination in the Hindi file.
  7. Every component named in AndroidManifest.xml exists as a Java file.
  8. Every custom view class used in a layout exists.
  9. Every `com.focuslife.app.*` import resolves to a real source file, a
     generated R/BuildConfig, or a ViewBinding with a matching layout.

Exit code is non-zero when anything is missing, so it can gate a commit.
"""

import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")
JAVA = os.path.join(ROOT, "app", "src", "main", "java")
MANIFEST = os.path.join(ROOT, "app", "src", "main", "AndroidManifest.xml")

problems = []
notes = []


def fail(msg):
    problems.append(msg)


# ----------------------------------------------------------------------
#  Collect declared resources
# ----------------------------------------------------------------------

declared = defaultdict(set)

for entry in sorted(os.listdir(RES)):
    path = os.path.join(RES, entry)
    if not os.path.isdir(path):
        continue
    res_type = entry.split("-")[0]  # values-hi -> values, drawable-v24 -> drawable

    if res_type == "values":
        for fname in sorted(os.listdir(path)):
            if not fname.endswith(".xml"):
                continue
            text = open(os.path.join(path, fname), encoding="utf-8").read()
            for m in re.finditer(
                    r'<(string|color|dimen|style|bool|integer|attr|item|string-array|'
                    r'integer-array|array)\b[^>]*name="([^"]+)"', text):
                kind, name = m.group(1), m.group(2)
                if kind == "item":
                    declared["values_item"].add(name)
                else:
                    declared[kind].add(name)
        continue

    for fname in sorted(os.listdir(path)):
        if fname.endswith(".xml") or fname.endswith(".png") or fname.endswith(".webp"):
            declared[res_type].add(os.path.splitext(fname)[0])

# Style parent references imply child styles: Widget.FocusLife.Card.Accent
# also makes R.style.Widget_FocusLife_Card_Accent valid without a <style> tag.
for style in list(declared["style"]):
    parts = style.split(".")
    for i in range(1, len(parts) + 1):
        declared["style"].add("_".join(parts[:i]))

# Styles declared with dots also exist under the dotted R.style spelling.
for style in list(declared["style"]):
    declared["style"].add(style.replace(".", "_"))

# A <style name="A.B.C"> implies A.B and A exist for parent references.
for style in list(declared["style"]):
    parts = style.replace("_", ".").split(".")
    for i in range(1, len(parts) + 1):
        declared["style"].add("_".join(parts[:i]))
        declared["style"].add(".".join(parts[:i]))

# `@+id/x` is a declaration, and ids are auto-generated by aapt2 rather than
# listed in a values file, so they must be harvested from every XML file.
for dirpath, _d, filenames in os.walk(RES):
    for fname in filenames:
        if not fname.endswith(".xml"):
            continue
        text = open(os.path.join(dirpath, fname), encoding="utf-8").read()
        for m in re.finditer(r'@\+id/([A-Za-z_][A-Za-z0-9_]*)', text):
            declared["id"].add(m.group(1))

print(f"declared: {sum(len(v) for v in declared.values())} resource names "
      f"across {len(declared)} types")

# ----------------------------------------------------------------------
#  1. R.<type>.<name> references in Java
# ----------------------------------------------------------------------

R_TO_TYPE = {
    "string": "string", "strings": "string",
    "drawable": "drawable", "drawables": "drawable",
    "color": "color", "colors": "color",
    "dimen": "dimen", "dimens": "dimen",
    "style": "style", "styles": "style",
    "layout": "layout", "layouts": "layout",
    "id": "id", "ids": "id",
    "menu": "menu", "menus": "menu",
    "xml": "xml", "anim": "anim", "anims": "anim",
    "mipmap": "mipmap", "array": "array", "attr": "attr",
    "bool": "bool", "integer": "integer",
    "raw": "raw", "font": "font", "plurals": "plurals",
}

java_files = []
for dirpath, _dirnames, filenames in os.walk(JAVA):
    for fname in filenames:
        if fname.endswith(".java"):
            java_files.append(os.path.join(dirpath, fname))
java_files.sort()

r_refs = defaultdict(set)  # (type, name) -> files
for path in java_files:
    text = open(path, encoding="utf-8").read()
    # R.string.foo, R.style.TextAppearance_FocusLife_Body, R.drawable.ic_add
    # `(?<!android\.)` skips the framework's own android.R.attr.* references,
    # which legitimately do not exist in this project's res/.
    for m in re.finditer(r'(?<!android\.)(?<!\.)\bR\.(string|drawable|color|dimen|style|layout|id|menu|xml|anim'
                         r'|mipmap|array|bool|integer|attr|plurals|raw)\.([A-Za-z_][A-Za-z0-9_]*)',
                         text):
        rtype, name = m.group(1), m.group(2)
        r_refs[(rtype, name)].add(os.path.relpath(path, ROOT))

missing_r = []
for (rtype, name), files in sorted(r_refs.items()):
    pool = declared.get(rtype, set())
    if name not in pool:
        # R.style accepts both dot and underscore spellings.
        if rtype == "style" and name.replace("_", ".") in pool:
            continue
        missing_r.append((rtype, name, sorted(files)))

if missing_r:
    for rtype, name, files in missing_r:
        fail(f"R.{rtype}.{name} referenced but not declared "
             f"({', '.join(os.path.basename(f) for f in files[:3])}"
             f"{'...' if len(files) > 3 else ''})")
else:
    print(f"OK: all {len(r_refs)} distinct R.* references resolve")

# ----------------------------------------------------------------------
#  2. @type/name references in XML
# ----------------------------------------------------------------------

xml_files = []
for dirpath, _dirnames, filenames in os.walk(RES):
    for fname in filenames:
        if fname.endswith(".xml"):
            xml_files.append(os.path.join(dirpath, fname))
xml_files.append(MANIFEST)
xml_files.sort()

# Resources that live in the Material / AppCompat / ConstraintLayout libraries
# rather than in this project's res/. They are real at build time and must not be
# reported as missing.
LIBRARY_RESOURCES = {
    ("string", "appbar_scrolling_view_behavior"),
    ("string", "bottom_sheet_behavior"),
    ("string", "character_counter_content_description"),
    ("string", "fab_transformation_scrim_behavior"),
    ("string", "fab_transformation_sheet_behavior"),
    ("string", "hide_bottom_view_on_scroll_behavior"),
    ("string", "mtrl_checkbox_state_description_checked"),
    ("string", "path_password_eye"),
    ("string", "search_menu_title"),
    ("style", "Widget.Design.AppBarLayout"),
    ("style", "ThemeOverlay.Material3"),
    ("dimen", "design_bottom_navigation_height"),
    ("color", "mtrl_btn_text_color_selector"),
}

at_refs = defaultdict(set)
for path in xml_files:
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r'@(string|drawable|color|dimen|style|layout|menu|xml|anim|mipmap'
                         r'|array|integer|bool|font|raw)/([A-Za-z_][A-Za-z0-9_.]*)', text):
        at_refs[(m.group(1), m.group(2))].add(os.path.relpath(path, ROOT))

# @+id/x are declarations, not references, and @id/x inside layouts are checked
# separately against ids declared somewhere.
declared_ids = set()
for path in xml_files:
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r'@\+id/([A-Za-z_][A-Za-z0-9_]*)', text):
        declared_ids.add(m.group(1))

missing_at = []
for (rtype, name), files in sorted(at_refs.items()):
    base = name.split(".")[0]
    pool = declared.get(rtype, set())
    if name not in pool and base not in pool:
        if rtype == "style" and name.replace("_", ".") in pool:
            continue
        if (rtype, name) in LIBRARY_RESOURCES:
            continue
        missing_at.append((rtype, name, sorted(files)))

if missing_at:
    for rtype, name, files in missing_at:
        fail(f"@{rtype}/{name} referenced but not declared "
             f"({', '.join(os.path.basename(f) for f in files[:3])}"
             f"{'...' if len(files) > 3 else ''})")
else:
    print(f"OK: all {len(at_refs)} distinct @type/name references resolve")

# @id/x (no +) must be declared somewhere
for path in xml_files:
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r'@id/([A-Za-z_][A-Za-z0-9_]*)', text):
        if m.group(1) not in declared_ids:
            fail(f"@id/{m.group(1)} used but never declared as @+id "
                 f"in {os.path.basename(path)}")

# ----------------------------------------------------------------------
#  3. Custom view attributes declared in attrs.xml
# ----------------------------------------------------------------------

CUSTOM_NS_PREFIXES = ("prv_", "bcv_", "wsv_")
for path in xml_files:
    text = open(path, encoding="utf-8").read()
    if "res/values" in path:
        continue
    for m in re.finditer(r'\bapp:([a-zA-Z_][A-Za-z0-9_]*)=', text):
        attr = m.group(1)
        if attr.startswith(CUSTOM_NS_PREFIXES):
            if attr not in declared["attr"]:
                fail(f"app:{attr} used in {os.path.basename(path)} "
                     f"but not declared in values/attrs.xml")

# ----------------------------------------------------------------------
#  4. ViewBinding: layout ids <-> binding field usage
# ----------------------------------------------------------------------

def binding_field(xml_id):
    """snake_case id -> camelCase ViewBinding field."""
    parts = xml_id.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def camel_to_snake(field):
    out = []
    for index, ch in enumerate(field):
        if ch.isupper():
            # No separator before a leading capital, and none inside a run of
            # capitals ("tvABCLabel" -> "tv_abc_label", not "tv_a_b_c_label").
            if index > 0 and not (field[index - 1].isupper()
                                  and (index + 1 >= len(field) or not field[index + 1].islower())):
                out.append("_")
            out.append(ch.lower())
        else:
            out.append(ch)
    return "".join(out)


# map layout file -> set of ids
layout_ids = {}
layout_dir = os.path.join(RES, "layout")
if os.path.isdir(layout_dir):
    for fname in sorted(os.listdir(layout_dir)):
        if not fname.endswith(".xml"):
            continue
        text = open(os.path.join(layout_dir, fname), encoding="utf-8").read()
        layout_ids[fname[:-4]] = {m.group(1) for m in
                                  re.finditer(r'android:id="@\+id/([A-Za-z_][A-Za-z0-9_]*)"', text)}

# <include android:id="@+id/x"> gives the binding a field of the include id whose
# type is the included layout's binding, so ids inside the included layout are
# NOT directly reachable. Track those separately.
included_roots = {}
for layout, ids in layout_ids.items():
    text = open(os.path.join(layout_dir, layout + ".xml"), encoding="utf-8").read()
    for m in re.finditer(r'<include\b[^>]*android:id="@\+id/([A-Za-z_][A-Za-z0-9_]*)"'
                         r'[^>]*layout="@layout/([A-Za-z_][A-Za-z0-9_]*)"', text, re.S):
        included_roots[(layout, m.group(1))] = m.group(2)
    for m in re.finditer(r'<include\b[^>]*layout="@layout/([A-Za-z_][A-Za-z0-9_]*)"'
                         r'[^>]*android:id="@\+id/([A-Za-z_][A-Za-z0-9_]*)"', text, re.S):
        included_roots[(layout, m.group(2))] = m.group(1)

# Resolve which *variable* holds which binding class. Guessing from a field name
# alone is wrong: a DiffUtil callback routinely names its second entity argument
# `b`, and a fragment may hold three different bindings at once.
DECL_RE = re.compile(r'\b([A-Z][A-Za-z0-9]*)Binding\s+(?:final\s+)?([a-z][A-Za-z0-9]*)\b')
ACCESS_RE = re.compile(r'\b([a-z][A-Za-z0-9]*)\.([a-z][A-Za-z0-9]*)\b')

# A nested binding reached through an <include> exposes the included layout's
# fields under the include's own id.
def available_fields(layout_names):
    """Union of ViewBinding field names reachable from the given layouts."""
    fields = set()
    for layout in layout_names:
        if layout not in layout_ids:
            continue
        for xml_id in layout_ids[layout]:
            fields.add(binding_field(xml_id))
        for (owner, inc_id), inc_layout in included_roots.items():
            if owner != layout:
                continue
            fields.add(binding_field(inc_id))
            for nested_id in layout_ids.get(inc_layout, ()):
                fields.add(binding_field(nested_id))
    return fields


def binding_class_to_layout(binding_class):
    """FragmentHomeBinding -> fragment_home, ItemHabitBinding -> item_habit."""
    snake = camel_to_snake(binding_class)
    if snake in layout_ids:
        return [snake]
    # Fall back to a suffix match so `activity_main` also satisfies a class
    # generated for a differently-prefixed layout.
    return [k for k in layout_ids if k == snake or k.endswith("_" + snake)]


# Layouts an adapter/viewholder inflates explicitly by name.
INFLATE_RE = re.compile(r'\b([A-Z][A-Za-z0-9]*)Binding\.inflate\b')

for path in java_files:
    text = open(path, encoding="utf-8").read()
    if "Binding" not in text:
        continue

    var_to_layouts = {}
    for m in DECL_RE.finditer(text):
        binding_class, var = m.group(1), m.group(2)
        layouts = binding_class_to_layout(binding_class)
        if not layouts:
            fail(f"{os.path.basename(path)}: no res/layout file matches "
                 f"{binding_class}Binding (expected "
                 f"{camel_to_snake(binding_class)}.xml)")
            continue
        var_to_layouts.setdefault(var, set()).update(layouts)

    # findViewById(R.id.x) and inflate() calls reach layouts not held in a field.
    extra_layouts = set()
    for m in INFLATE_RE.finditer(text):
        extra_layouts.update(binding_class_to_layout(m.group(1)))
    for m in re.finditer(r'R\.layout\.([A-Za-z_][A-Za-z0-9_]*)', text):
        if m.group(1) in layout_ids:
            extra_layouts.add(m.group(1))
        else:
            fail(f"{os.path.basename(path)}: R.layout.{m.group(1)} has no layout file")

    for var, layouts in var_to_layouts.items():
        fields = available_fields(layouts | extra_layouts)
        for m in ACCESS_RE.finditer(text):
            if m.group(1) != var:
                continue
            field = m.group(2)
            if field in fields:
                continue
            # Root view and framework members are not ids.
            if field in {"getRoot", "inflate", "bind", "root"}:
                continue
            fail(f"{os.path.basename(path)}: `{var}.{field}` has no android:id in "
                 f"{', '.join(sorted(layouts))}.xml")

# ----------------------------------------------------------------------
#  5/6. String parity + placeholders + CJK
# ----------------------------------------------------------------------

def load_strings(path):
    text = open(path, encoding="utf-8").read()
    return dict(re.findall(r'<string name="([^"]+)">(.*?)</string>', text, re.S))


en_path = os.path.join(RES, "values", "strings.xml")
hi_path = os.path.join(RES, "values-hi", "strings.xml")
en = load_strings(en_path)
hi = load_strings(hi_path)

missing_hi = [k for k in en if k not in hi]
extra_hi = [k for k in hi if k not in en]
if missing_hi:
    fail(f"{len(missing_hi)} strings missing from values-hi: {missing_hi[:8]}")
if extra_hi:
    fail(f"{len(extra_hi)} strings only in values-hi: {extra_hi[:8]}")

PH = re.compile(r'%(\d+\$[a-zA-Z])')
placeholder_bad = [k for k in en if k in hi and sorted(PH.findall(en[k])) != sorted(PH.findall(hi[k]))]
if placeholder_bad:
    fail(f"placeholder mismatch en/hi: {placeholder_bad[:8]}")

# Positional placeholders are mandatory when a string has 2+ substitutions,
# otherwise translators reorder words and the args land in the wrong slot.
NON_POSITIONAL = re.compile(r'%[a-zA-Z]')
bad_positional = []
for k, v in en.items():
    subs = NON_POSITIONAL.findall(v)
    positional = PH.findall(v)
    if len(subs) > len(positional) and len(subs) >= 2:
        bad_positional.append(k)
if bad_positional:
    fail(f"{len(bad_positional)} strings use non-positional %s/%d with 2+ args "
         f"(must be %1$s): {bad_positional[:8]}")

CJK = re.compile(r'[\u3000-\u303f\u4e00-\u9fff\u3040-\u30ff]')
cjk_bad = [(k, CJK.search(v).group(0)) for k, v in hi.items() if CJK.search(v)]
if cjk_bad:
    fail(f"CJK characters in values-hi (must be Devanagari only): {cjk_bad[:8]}")

DEVANAGARI = re.compile(r'[\u0900-\u097f]')
untranslated = [k for k, v in hi.items()
                if not DEVANAGARI.search(v) and re.search(r'[A-Za-z]{3}', v)
                and k not in {"app_name"}]
notes.append(f"{len(untranslated)} Hindi strings contain no Devanagari "
             f"(proper nouns/units are legitimate): {untranslated[:12]}")

if not (missing_hi or extra_hi or placeholder_bad or cjk_bad or bad_positional):
    print(f"OK: {len(en)} strings in full en/hi parity, placeholders match, no CJK")

# Duplicate <string name> within one file silently keeps the last one.
for path, label in ((en_path, "values"), (hi_path, "values-hi")):
    text = open(path, encoding="utf-8").read()
    names = re.findall(r'<string name="([^"]+)"', text)
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        fail(f"duplicate <string> entries in {label}: {sorted(dupes)[:8]}")

# ----------------------------------------------------------------------
#  6b. Format-argument verification
# ----------------------------------------------------------------------
# A wrong argument count or type in getString() does not fail the build: it
# throws MissingFormatArgumentException or IllegalFormatConversionException at
# runtime, on whichever screen the user happens to open. With no device to test
# on, this is the single highest-value static check in the project.

ARG_TYPE = {"s": str, "d": int, "f": float}

# Collect (string name -> list of positional specifiers in order).
string_specs = {}
for name, value in en.items():
    string_specs[name] = PH.findall(value)
    # Also record bare (non-positional) specifiers so they can be reported.
    bare = NON_POSITIONAL.findall(value)
    positional = PH.findall(value)
    if len(bare) > len(positional):
        string_specs[name] = None  # unusable for positional checking


def classify_argument(expr):
    """Best-effort static type of a Java expression passed to getString()."""
    expr = expr.strip()
    if re.fullmatch(r'-?\d+[lL]?', expr):
        return "d"
    if re.fullmatch(r'-?\d+\.\d+[fFdD]?', expr):
        return "f"
    if expr.startswith('"'):
        return "s"
    if re.search(r'\.(length|size)\(\)', expr):
        return "d"
    if re.search(r'\b(Integer\.parseInt|Long\.parseLong)\b', expr):
        return "d"
    if re.search(r'\b(Integer\.valueOf|Long\.valueOf)\b', expr):
        return "d"
    if re.search(r'\b(TimeUtils|ModeController|Repository)\.[a-zA-Z]+\(', expr):
        return "s"
    if re.search(r'\bgetString\(', expr):
        return "s"
    if re.search(r'\.toString\(\)', expr):
        return "s"
    if re.search(r'\b(String|CharSequence)\b', expr):
        return "s"
    if re.search(r'\bMath\.(round|max|min|abs)\(', expr):
        return "d"
    # A bare lowercase identifier: infer from declared Java types where possible.
    return None


# Split a Java argument list on top-level commas.
def split_args(text):
    depth = 0
    parts = []
    current = []
    in_string = False
    escape = False
    for ch in text:
        if escape:
            current.append(ch)
            escape = False
            continue
        if ch == "\\":
            current.append(ch)
            escape = True
            continue
        if ch == '"' and not escape:
            in_string = not in_string
            current.append(ch)
            continue
        if not in_string:
            if ch in "([{":
                depth += 1
            elif ch in ")]}":
                depth -= 1
            elif ch == "," and depth == 0:
                parts.append("".join(current))
                current = []
                continue
        current.append(ch)
    if current:
        parts.append("".join(current))
    return [p.strip() for p in parts if p.strip()]


CALL_RE = re.compile(
    r'(?:getString|getResources\(\)\.getString|getApplicationContext\(\)\.getString)'
    r'\(\s*R\.string\.([A-Za-z_][A-Za-z0-9_]*)\s*((?:,)?)', re.S)

format_problems = 0
for path in java_files:
    text = open(path, encoding="utf-8").read()
    for m in CALL_RE.finditer(text):
        name = m.group(1)
        has_args = m.group(2) == ","
        specs = string_specs.get(name)

        if specs is None and name in en:
            # Non-positional placeholders: count them instead.
            declared = len(NON_POSITIONAL.findall(en[name]))
            if declared >= 2:
                fail(f"{os.path.basename(path)}: getString(R.string.{name}) — that string "
                     f"uses {declared} non-positional %s/%d and must be rewritten "
                     f"positionally (%1$s) before it can be formatted safely")
                format_problems += 1
            continue

        if name not in string_specs:
            continue  # already reported as a missing resource

        if not has_args:
            # setText(R.string.x) with no args is checked separately; here only
            # flag getString() called without arguments on a formatted string.
            if specs:
                fail(f"{os.path.basename(path)}: getString(R.string.{name}) passed no "
                     f"arguments but the string needs {len(specs)} "
                     f"({', '.join(specs)}) — it would print the raw %1$s")
                format_problems += 1
            continue

        # Walk the arguments after R.string.name.
        start = m.end()
        depth = 1
        index = start
        while index < len(text) and depth > 0:
            ch = text[index]
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            index += 1
        arg_text = text[start:index - 1]
        args = split_args(arg_text)

        if len(args) != len(specs):
            fail(f"{os.path.basename(path)}: getString(R.string.{name}, ...) passes "
                 f"{len(args)} argument(s) but the string declares {len(specs)} "
                 f"({', '.join(specs) or 'none'})")
            format_problems += 1
            continue

        for i, spec in enumerate(specs):
            kind = spec[-1]
            actual = classify_argument(args[i])
            if actual is not None and actual != kind:
                fail(f"{os.path.basename(path)}: getString(R.string.{name}, ...) argument "
                     f"{i + 1} is '{args[i][:40]}' (looks like %{actual}) but the string "
                     f"expects %{spec}")
                format_problems += 1

# setText(R.string.x) on a string that needs arguments prints the placeholder.
for path in java_files:
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r'\.setText\(\s*R\.string\.([A-Za-z_][A-Za-z0-9_]*)\s*\)', text):
        name = m.group(1)
        if name in string_specs and string_specs[name]:
            fail(f"{os.path.basename(path)}: setText(R.string.{name}) but that string "
                 f"needs {len(string_specs[name])} argument(s) "
                 f"({', '.join(string_specs[name])}) — it would render the raw placeholder")
            format_problems += 1
    for m in re.finditer(r'android:text="@string/([A-Za-z_][A-Za-z0-9_]*)"', text):
        pass

if format_problems == 0:
    print("OK: every getString/setText call matches its string's format specifiers")

# XML android:text / tools:text pointing at a formatted string renders the raw
# placeholder on screen (tools:text is fine, it is stripped at build time).
for path in xml_files:
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(r'(?<!tools:)android:text="@string/([A-Za-z_][A-Za-z0-9_]*)"', text):
        name = m.group(1)
        if name in string_specs and string_specs[name]:
            fail(f"{os.path.basename(path)}: android:text=\"@string/{name}\" but that string "
                 f"needs {len(string_specs[name])} argument(s) — it would render "
                 f"the raw placeholder")
            format_problems += 1

# ----------------------------------------------------------------------
#  7. Manifest components exist
# ----------------------------------------------------------------------

manifest_text = open(MANIFEST, encoding="utf-8").read()
pkg = re.search(r'package="([^"]+)"', manifest_text)
# AGP 8 takes the namespace from build.gradle; components are dotted names.
component_re = re.compile(r'android:name="(\.[A-Za-z0-9_.]+|[a-z][A-Za-z0-9_.]*\.[A-Za-z0-9_.]+)"')
missing_components = []
for m in component_re.finditer(manifest_text):
    name = m.group(1)
    if name.startswith("androidx.") or name.startswith("com.google.") or name.startswith("android."):
        continue
    rel = name[1:] if name.startswith(".") else name
    java_path = os.path.join(JAVA, "com", "focuslife", "app", rel.replace(".", os.sep) + ".java")
    if not os.path.exists(java_path):
        missing_components.append(name)
if missing_components:
    fail(f"manifest declares components with no source file: {missing_components}")
else:
    print("OK: every manifest component has a source file")

